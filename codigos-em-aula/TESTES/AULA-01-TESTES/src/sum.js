export function sum(a, b) {
    return a+b
}


export function mult(a, b) {
    return a*b
}

export function divisao(a, b) {
    return a/b
}

export function subtracao(a, b) {
    return a-b
}


export function integral(x, n) {
    return (x ** (n + 1)) / (n + 1);
}

export function derivada(x, n) {
    return n * (x ** (n - 1));
}

